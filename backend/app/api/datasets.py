"""Dataset upload, profiling, ingestion and sample-dataset endpoints."""

from __future__ import annotations

import logging
import os
from typing import Any, Dict, Optional

from fastapi import APIRouter, Depends, File, HTTPException, Query, Request, UploadFile, status
from fastapi.responses import FileResponse, Response

from app.api.common import Paging, envelope, paging_params, service_error
from app.core.config import settings
from app.security.deps import client_ip, get_current_user, require_capability
from app.security.ratelimit import limiter
from app.services import audit_service, dataset_service, forecast_service, model_service, pipeline_service

logger = logging.getLogger("cyberforecast.api.datasets")
router = APIRouter(prefix="/datasets", tags=["Datasets"])


@router.get("/samples")
def samples(user: Dict[str, Any] = Depends(get_current_user)) -> Dict[str, Any]:
    """Bundled sample datasets available for one-click analysis."""
    items = dataset_service.sample_datasets()
    return {
        "items": items,
        "note": "Synthetic, defense-oriented sample data generated by backend/scripts/generate_sample_dataset.py",
        "limits": {"max_upload_mb": settings.max_upload_mb, "allowed": settings.allowed_upload_extensions},
    }


@router.post("/samples/{name}/ingest")
def ingest_sample(name: str, request: Request,
                  run_analysis: bool = Query(True),
                  user: Dict[str, Any] = Depends(require_capability("datasets.upload"))) -> Dict[str, Any]:
    match = next((item for item in dataset_service.sample_datasets() if item["name"] == name), None)
    if not match:
        raise HTTPException(status_code=404, detail=f"Sample dataset '{name}' is not available.")
    with open(match["path"], "rb") as handle:
        content = handle.read()
    try:
        record = dataset_service.ingest(match["name"], content, user=user, run_analysis=run_analysis)
    except Exception as exc:
        raise service_error(exc)
    pipeline_service.record_dataset_event(record, user)
    audit_service.log("dataset.sample_ingested", category="dataset", user=user, resource="dataset",
                      resource_id=record["id"], metadata={"filename": match["name"], "rows": record.get("rows")},
                      ip_address=client_ip(request))
    return record


@router.post("/upload", status_code=status.HTTP_201_CREATED)
@limiter.limit("20/minute")
async def upload(request: Request, file: UploadFile = File(...),
                 run_analysis: bool = Query(True, description="Analyze immediately after upload"),
                 analysis_limit: Optional[int] = Query(None, ge=1, le=200000),
                 user: Dict[str, Any] = Depends(require_capability("datasets.upload"))) -> Dict[str, Any]:
    content = await file.read()
    try:
        record = dataset_service.ingest(
            file.filename or "upload.csv", content, user=user,
            run_analysis=run_analysis, analysis_limit=analysis_limit,
        )
    except Exception as exc:
        audit_service.log("dataset.upload_failed", category="dataset", user=user, outcome="failure",
                          metadata={"filename": file.filename, "reason": str(exc)[:200]},
                          ip_address=client_ip(request))
        raise service_error(exc)
    pipeline_service.record_dataset_event(record, user)
    audit_service.log("dataset.uploaded", category="dataset", user=user, resource="dataset",
                      resource_id=record["id"],
                      metadata={"filename": record.get("original_filename"), "rows": record.get("rows"),
                                "columns": record.get("columns"), "size_bytes": record.get("size_bytes"),
                                "storage_backend": record.get("storage_backend")},
                      ip_address=client_ip(request))
    return record


@router.get("")
def list_datasets(paging: Paging = Depends(paging_params), search: Optional[str] = Query(None),
                  mine_only: bool = Query(False),
                  user: Dict[str, Any] = Depends(get_current_user)) -> Dict[str, Any]:
    rows, total = dataset_service.list_datasets(
        limit=paging.limit, offset=paging.offset,
        user_id=user["id"] if mine_only else None, search=search,
    )
    for row in rows:
        profile = row.get("profile") or {}
        row["profile_summary"] = {
            "rows": profile.get("rows", row.get("rows")),
            "columns": profile.get("columns", row.get("columns")),
            "missing_value_total": profile.get("missing_value_total"),
            "duplicate_rows": profile.get("duplicate_rows"),
            "schema_coverage": profile.get("schema_coverage"),
            "labeled": profile.get("labeled"),
            "class_distribution": profile.get("class_distribution"),
        }
        row.pop("profile", None)
    return envelope(rows, total, paging)


@router.get("/{dataset_id}")
def get_dataset(dataset_id: str, include_profile: bool = Query(True),
                user: Dict[str, Any] = Depends(get_current_user)) -> Dict[str, Any]:
    record = dataset_service.get_dataset(dataset_id)
    if not record:
        raise HTTPException(status_code=404, detail="Dataset not found.")
    if not include_profile:
        record.pop("profile", None)
    return record


@router.get("/{dataset_id}/download")
def download(dataset_id: str, user: Dict[str, Any] = Depends(require_capability("datasets.manage"))) -> Response:
    record = dataset_service.get_dataset(dataset_id)
    if not record:
        raise HTTPException(status_code=404, detail="Dataset not found.")
    path = dataset_service.local_path(record.get("filename") or "")
    if record.get("storage_backend") == "bundled-path" or os.path.isabs(record.get("filename") or ""):
        path = record.get("filename")
    if not path or not os.path.isfile(path):
        raise HTTPException(status_code=410, detail="The stored file is no longer available on this instance.")
    return FileResponse(path, filename=record.get("original_filename") or os.path.basename(path),
                        media_type="text/csv" if record.get("file_format") == "csv" else "application/json")


@router.post("/{dataset_id}/analyze")
def analyze_dataset(dataset_id: str, request: Request,
                    limit: int = Query(5000, ge=10, le=200000),
                    create_alerts: bool = Query(True),
                    user: Dict[str, Any] = Depends(require_capability("predict.run"))) -> Dict[str, Any]:
    record = dataset_service.get_dataset(dataset_id)
    if not record:
        raise HTTPException(status_code=404, detail="Dataset not found.")
    raw = dataset_service.read_raw_frame(record)
    if raw is None or raw.empty:
        raise HTTPException(status_code=410, detail="Dataset content is not readable on this instance.")
    from app.ml.features import detect_columns, normalize_frame

    normalized = normalize_frame(raw, detect_columns(raw)).drop_duplicates().head(limit)
    result = pipeline_service.analyze_frame(
        normalized, dataset_id=dataset_id, source="dataset", persist=True,
        create_alerts=create_alerts, explain=True, max_explanations=200, user=user,
    )
    audit_service.log("dataset.analyzed", category="prediction", user=user, resource="dataset",
                      resource_id=dataset_id, metadata={"rows": len(normalized),
                                                        "attacks": (result.get("summary") or {}).get("attacks_detected")},
                      ip_address=client_ip(request))
    return result


@router.post("/{dataset_id}/forecast")
def forecast_dataset(dataset_id: str, request: Request,
                     user: Dict[str, Any] = Depends(require_capability("forecast.run"))) -> Dict[str, Any]:
    try:
        payload = forecast_service.run_forecast(dataset_id=dataset_id, persist=True, create_alerts=False, user=user)
    except Exception as exc:
        raise service_error(exc)
    audit_service.log("forecast.dataset_run", category="prediction", user=user, resource="dataset",
                      resource_id=dataset_id, metadata={"run_id": payload.get("run_id")}, ip_address=client_ip(request))
    return payload


@router.post("/{dataset_id}/train")
def train_on_dataset(dataset_id: str, request: Request,
                     algorithm: str = Query(settings.default_classifier),
                     activate: bool = Query(False),
                     user: Dict[str, Any] = Depends(require_capability("models.train"))) -> Dict[str, Any]:
    try:
        result = model_service.train(algorithm=algorithm, dataset_id=dataset_id, user=user)
        if activate:
            for record in result.get("trained", []):
                if record.get("task") == "classification":
                    model_service.activate(record["id"], user=user, dataset_id=dataset_id)
    except Exception as exc:
        audit_service.log("model.train_failed", category="model", user=user, outcome="failure",
                          metadata={"dataset_id": dataset_id, "reason": str(exc)[:200]}, ip_address=client_ip(request))
        raise service_error(exc, default_status=500)
    audit_service.log("model.trained", category="model", user=user, resource="dataset", resource_id=dataset_id,
                      metadata={"algorithm": algorithm, "models": [r["id"] for r in result.get("trained", [])]},
                      ip_address=client_ip(request))
    return result


@router.get("/{dataset_id}/preview")
def preview_dataset(dataset_id: str, limit: int = Query(25, ge=1, le=200),
                    user: Dict[str, Any] = Depends(get_current_user)) -> Dict[str, Any]:
    """Normalized sample rows plus the detected column mapping for the analyzer UI."""
    try:
        result = dataset_service.preview(dataset_id, limit=limit)
    except Exception as exc:
        raise service_error(exc)
    if result is None:
        raise HTTPException(status_code=404, detail="Dataset not found.")
    return result


@router.post("/{dataset_id}/profile")
@limiter.limit("12/minute")
def reprofile_dataset(dataset_id: str, request: Request,
                      user: Dict[str, Any] = Depends(require_capability("datasets.upload"))) -> Dict[str, Any]:
    """Recompute the stored quality profile (useful for bundled samples)."""
    try:
        record = dataset_service.reprofile(dataset_id)
    except Exception as exc:
        raise service_error(exc)
    if record is None:
        raise HTTPException(status_code=404, detail="Dataset not found.")
    audit_service.log("dataset.reprofiled", category="dataset", user=user, resource="dataset",
                      resource_id=dataset_id, metadata={"rows": record.get("rows"), "columns": record.get("columns")},
                      ip_address=client_ip(request))
    return record


@router.delete("/{dataset_id}")
def delete_dataset(dataset_id: str, request: Request,
                   user: Dict[str, Any] = Depends(require_capability("datasets.manage"))) -> Dict[str, Any]:
    if not dataset_service.delete_dataset(dataset_id):
        raise HTTPException(status_code=404, detail="Dataset not found.")
    audit_service.log("dataset.deleted", category="dataset", user=user, resource="dataset",
                      resource_id=dataset_id, ip_address=client_ip(request))
    return {"ok": True, "deleted": dataset_id}
